		const triaged = new Set<string>([...CLAUDE_SEAT_PASSTHROUGH_ENV_VARS, ...DEFAULT_AGENT_ENV_ALLOWLIST, ...EXCLUDED.flatMap((entry) => entry.names)]);
		const untriaged = [...extracted].filter((name) => !triaged.has(name)).sort();
