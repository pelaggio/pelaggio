/**
 * SDK env-surface conformance (#554). Three review rounds of "the SDK also consumes X"
 * (Bedrock selectors, then WIF/federated credentials, then profile auth) proved the
 * hand-enumerated seat allowlists have a long tail. This test extracts every env-var name
 * the INSTALLED `@anthropic-ai/claude-agent-sdk` mentions - a conservative string scan
 * (provider-prefix literals + `process.env` accesses); no SDK code is executed - and
 * asserts each name is TRIAGED: forwarded/gated by the seat lists, on the shared default
 * allowlist, or explicitly reviewed-and-excluded below with a reason. An SDK bump that
 * introduces an un-triaged name fails HERE at bump time instead of surfacing as a fleet
 * review finding three PRs later.
 */
import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { describe, it } from "node:test";
import { CLAUDE_SEAT_PASSTHROUGH_ENV_VARS } from "../claude-seat.js";
import { DEFAULT_AGENT_ENV_ALLOWLIST } from "../secret-hygiene.js";

const require = createRequire(import.meta.url);
// The SDK's exports map hides package.json; its main entry (sdk.mjs) sits at the package root.
const SDK_ROOT = dirname(require.resolve("@anthropic-ai/claude-agent-sdk"));

const PROVIDER_PREFIX_RE = /\b(?:ANTHROPIC|CLAUDE_CODE|CLAUDE_AGENT|AWS|GOOGLE|GCLOUD|CLOUD_ML)_[A-Z0-9_]+\b/g;
const ENV_ACCESS_RE = /process\.env(?:\.([A-Za-z_][A-Za-z0-9_]*)|\[["']([^"'\]]+)["']\])/g;

function extractSdkEnvNames(): Set<string> {
	const names = new Set<string>();
	const walk = (dir: string): void => {
		for (const entry of readdirSync(dir)) {
			const path = join(dir, entry);
			if (statSync(path).isDirectory()) {
				// The SDK's own dependency tree is not part of its documented env contract.
				if (entry !== "node_modules") walk(path);
				continue;
			}
			if (!/\.(?:mjs|cjs|js)$/.test(entry)) continue;
			const text = readFileSync(path, "utf8");
			for (const match of text.matchAll(PROVIDER_PREFIX_RE)) names.add(match[0]);
			for (const match of text.matchAll(ENV_ACCESS_RE)) {
				const name = match[1] ?? match[2];
				if (name !== undefined) names.add(name);
			}
		}
	};
	walk(SDK_ROOT);
	return names;
}

